"""Collects every results JSON into figures and one markdown summary (results/summary.md)."""
import math

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt

import config
from lm.utils import load_json, results_dir

COLORS = {"ngram": "#7f7f7f", "rnn": "#d62728", "lstm": "#1f77b4", "transformer": "#2ca02c",
          "lstm_w2v": "#9467bd", "lstm_glove": "#ff7f0e",
          "lstm_frozen_random": "#8c564b"}
LABELS = {"ngram": "KN trigram", "rnn": "RNN", "lstm": "LSTM", "transformer": "Transformer",
          "lstm_w2v": "LSTM + own w2v (frozen)", "lstm_glove": "LSTM + GloVe (frozen)",
          "lstm_frozen_random": "LSTM + random (frozen)"}


def _load_runs(d):
    runs = {}
    for name in ["ngram", "rnn", "lstm", "transformer", "lstm_frozen_random", "lstm_w2v", "lstm_glove"]:
        p = d / "runs" / f"{name}.json"
        if p.exists():
            runs[name] = load_json(p)
    return runs


def _curves(runs, names, title, path):
    names = [n for n in names if n in runs and "history" in runs[n]]
    if not names:
        return
    fig, ax = plt.subplots(figsize=(6.4, 4.0))
    for n in names:
        h = runs[n]["history"]
        ep = [r["epoch"] for r in h]
        ax.plot(ep, [r["train_ce"] for r in h], "--", color=COLORS[n], alpha=0.8)
        ax.plot(ep, [r["valid_ce"] for r in h], "-", color=COLORS[n], label=LABELS[n])
        ax.axvline(runs[n]["best_epoch"], color=COLORS[n], lw=0.6, ls=":")
    ax.set_xlabel("epoch")
    ax.set_ylabel("cross-entropy (nats / token)")
    ax.set_title(title + "  (solid = validation, dashed = train)")
    ax.legend(frameon=False)
    ax.grid(alpha=0.3)
    fig.tight_layout()
    fig.savefig(path, dpi=200)
    plt.close(fig)


def _fmt(x, nd=1):
    return "–" if x is None else f"{x:,.{nd}f}"


def make_report(smoke: bool = False):
    d = results_dir(smoke)
    figs = d / "figures"
    runs = _load_runs(d)
    lines = ["# Results summary", "", "Auto-generated by `python run.py report`. "
             "All numbers come from the JSON files in `runs/` and `downstream/`.", ""]

    any_run = next(iter(runs.values()), None)
    if any_run:
        lines += ["## Corpus", "", "```", str(any_run["corpus"]), "```", ""]
        neural = [r for r in runs.values() if r["name"] != "ngram"]
        if neural:
            lines += ["## Hardware", "", "```", str(neural[0]["hardware"]), "```", "",
                      "## Run settings", "", "```", str(neural[0]["config"]), "```", ""]

    # ---------------------------------------------------------------- Part I
    p1 = [n for n in ["ngram", "rnn", "lstm", "transformer"] if n in runs]
    if p1:
        lines += ["## Part I — language models", "",
                  "| model | valid ppl | test ppl | params (total) | core params | size MB | "
                  "best epoch | train s | s/epoch | test tok/s | gen s |",
                  "|---|---|---|---|---|---|---|---|---|---|---|"]
        for n in p1:
            r = runs[n]
            if n == "ngram":
                size = f"{r['size']['stored_entries']:,} entries"
                lines.append(f"| {LABELS[n]} | {_fmt(r['valid_ppl'])} | {_fmt(r['test_ppl'])} | "
                             f"{size} | – | {r['size']['size_mb']} | – | {r['train_seconds']} | – | "
                             f"{_fmt(r['inference']['tokens_per_second'], 0)} | "
                             f"{r['generation_seconds']} |")
            else:
                p = r["params"]
                lines.append(f"| {LABELS[n]} | {_fmt(r['valid_ppl'])} | {_fmt(r['test_ppl'])} | "
                             f"{p['total']:,} | {p['core']:,} | {p['size_mb_fp32']} | "
                             f"{r['best_epoch']}/{r['config']['epochs']} | {r['train_seconds']} | "
                             f"{r['seconds_per_epoch']} | "
                             f"{_fmt(r['inference']['tokens_per_second'], 0)} | "
                             f"{r['generation_seconds']} |")
        lines += ["", "n-gram timings are on CPU; neural timings on the device listed above.", ""]
        _curves(runs, ["rnn", "lstm", "transformer"], "Part I",
                figs / "part1_learning_curves.png")
        lines += ["![Part I curves](figures/part1_learning_curves.png)", ""]

        lines += ["### Generation repetition (sampled / greedy)", "",
                  "| model | distinct-1 | distinct-2 | repeated-trigram rate (sampled) | "
                  "repeated-trigram rate (greedy) |", "|---|---|---|---|---|"]
        for n in p1 + [n for n in ["lstm_frozen_random", "lstm_w2v", "lstm_glove"] if n in runs]:
            s, g = runs[n]["sample_repetition"], runs[n]["greedy_repetition"]
            lines.append(f"| {LABELS[n]} | {s['distinct_1']} | {s['distinct_2']} | "
                         f"{s['repeated_trigram_rate']} | {g['repeated_trigram_rate']} |")
        lines.append("")

    # ---------------------------------------------------------------- Part II
    p2 = [n for n in ["lstm", "lstm_frozen_random", "lstm_w2v", "lstm_glove"] if n in runs]
    if len(p2) > 1:
        lines += ["## Part II — embedding variants (LSTM)", "",
                  "| setting | valid ppl | test ppl | trainable params | best epoch | "
                  "epoch-1 valid ppl | mean grad norm | max grad norm | clipped frac | "
                  "type cov. | token cov. |", "|---|---|---|---|---|---|---|---|---|---|---|"]
        for n in p2:
            r = runs[n]
            h = r["history"]
            cov = r.get("embedding_coverage") or {}
            gmean = sum(x["grad_norm_mean"] for x in h) / len(h)
            gmax = max(x["grad_norm_max"] for x in h)
            clip = sum(x["clipped_frac"] for x in h) / len(h)
            lines.append(f"| {LABELS[n]} | {_fmt(r['valid_ppl'])} | {_fmt(r['test_ppl'])} | "
                         f"{r['params']['trainable']:,} | {r['best_epoch']} | "
                         f"{_fmt(h[0]['valid_ppl'])} | {gmean:.3f} | {gmax:.3f} | {clip:.2f} | "
                         f"{cov.get('type_coverage', '–')} | {cov.get('token_coverage', '–')} |")
        w2v = d / "runs" / "w2v_training.json"
        if w2v.exists():
            w = load_json(w2v)
            lines += ["", f"Own word2vec training cost (separate from LM training): "
                          f"{w['train_seconds']} s on {w['hardware']}, {w['tokens']:,} tokens, "
                          f"params {w['params']}."]
        for n in ["lstm_frozen_random", "lstm_w2v", "lstm_glove"]:
            cov = (runs.get(n) or {}).get("embedding_coverage")
            if cov:
                lines += ["", f"**{LABELS[n]}** — missing types: {cov['missing_types']}; "
                              f"init: {cov['missing_init']}; most frequent missing: "
                              f"{', '.join(f'{w} ({c})' for w, c in cov['most_frequent_missing'][:12])}",
                          f"Embedding table changed during training: "
                          f"{runs[n]['embedding_changed_during_training']} (must be False)."]
        lines.append("")
        _curves(runs, p2, "Part II", figs / "part2_learning_curves.png")
        lines += ["![Part II curves](figures/part2_learning_curves.png)", ""]

    # ---------------------------------------------------------------- generations
    gen_models = [n for n in ["ngram", "rnn", "lstm", "transformer", "lstm_frozen_random", "lstm_w2v", "lstm_glove"]
                  if n in runs]
    if gen_models:
        lines += ["## Generated text (matched settings)", "",
                  f"Sampling: temperature {config.GEN_TEMPERATURE}, top-k {config.GEN_TOP_K}, "
                  f"{config.GEN_TOKENS} tokens, seed {config.GEN_SEED}+prompt index, "
                  f"<unk> banned = {config.GEN_BAN_UNK}. Greedy uses the same prompts.", ""]
        for i, prompt in enumerate(config.PROMPTS):
            lines += [f"**Prompt:** `{prompt}`", ""]
            for n in gen_models:
                lines.append(f"- *{LABELS[n]}* (sampled): {runs[n]['samples'][i]['continuation']}")
            for n in gen_models:
                lines.append(f"- *{LABELS[n]}* (greedy): {runs[n]['greedy'][i]['continuation']}")
            lines.append("")

    # ---------------------------------------------------------------- Part III
    ds_path = d / "downstream" / "summary.json"
    if ds_path.exists():
        ds = load_json(ds_path)
        res = ds["results"]
        lines += ["## Part III — AG News with frozen LM representations", "",
                  f"Train {ds['n_train']}, validation {ds['n_val']}, test {ds['n_test']}. "
                  f"Majority-class accuracy {ds['majority_baseline_acc']}. "
                  f"Test-text <unk> rate {ds['test_text_stats']['token_unk_rate']}, "
                  f"mean length {ds['test_text_stats']['mean_len']} tokens, "
                  f"truncated {ds['test_text_stats']['truncated_frac']}.", "",
                  "| representation | dim | LM test ppl | C | test accuracy | test macro-F1 | "
                  "per-class F1 (W/S/B/T) |", "|---|---|---|---|---|---|---|"]
        for k, r in res.items():
            lines.append(f"| {LABELS[r['model']]} · {r['pooling']} | {r['dim']} | "
                         f"{_fmt(r['lm_test_ppl'])} | {r['C']} | {r['test_accuracy']} | "
                         f"{r['test_macro_f1']} | {r['per_class_f1']} |")
        lines.append("")
        _downstream_figs(res, figs)
        lines += ["![Part III](figures/part3_downstream.png)", "",
                  "![LM vs downstream](figures/part3_ppl_vs_acc.png)", ""]
        if ds.get("errors"):
            e = ds["errors"]
            lines += ["### Disagreements between " + " and ".join(e["compared"]), "",
                      f"Counts: {e['counts']}", ""]
            for title, key in [("Only the first is right", "only_a_right"),
                               ("Only the second is right", "only_b_right"),
                               ("Both wrong", "both_wrong")]:
                lines += [f"**{title}**", ""]
                for ex in e[key]:
                    preds = ", ".join(f"{m}: {ex[m]}" for m in e["compared"])
                    lines.append(f"- [{ex['true']}] ({preds}) {ex['text']}")
                lines.append("")

    out = d / "summary.md"
    out.write_text("\n".join(lines), encoding="utf-8")
    print("wrote", out)


def _downstream_figs(res, figs):
    models = [m for m in ["rnn", "lstm", "transformer", "lstm_frozen_random", "lstm_w2v", "lstm_glove"]
              if any(r["model"] == m for r in res.values())]
    pools = config.DOWNSTREAM_POOLING
    fig, ax = plt.subplots(figsize=(7.0, 3.8))
    w = 0.8 / len(pools)
    for j, p in enumerate(pools):
        vals = [res.get(f"{m}:{p}", {}).get("test_macro_f1", math.nan) for m in models]
        ax.bar([i + j * w for i in range(len(models))], vals, w, label=p)
    ax.set_xticks([i + w * (len(pools) - 1) / 2 for i in range(len(models))])
    ax.set_xticklabels([LABELS[m].replace(" (frozen)", "\n(frozen)") for m in models], fontsize=8)
    ax.set_ylabel("test macro-F1")
    lo = min(r["test_macro_f1"] for r in res.values())
    ax.set_ylim(max(0, lo - 0.05), 1.0)
    ax.legend(title="pooling", frameon=False, ncol=len(pools))
    ax.grid(axis="y", alpha=0.3)
    fig.tight_layout()
    fig.savefig(figs / "part3_downstream.png", dpi=200)
    plt.close(fig)

    fig, ax = plt.subplots(figsize=(5.2, 3.8))
    for m in models:
        r = res.get(f"{m}:mean")
        if r:
            ax.scatter(r["lm_test_ppl"], r["test_macro_f1"], color=COLORS[m], s=50)
            ax.annotate(LABELS[m], (r["lm_test_ppl"], r["test_macro_f1"]), fontsize=8,
                        xytext=(4, 4), textcoords="offset points")
    ax.set_xlabel("LM test perplexity (lower = better LM)")
    ax.set_ylabel("AG News test macro-F1 (mean pooling)")
    ax.grid(alpha=0.3)
    fig.tight_layout()
    fig.savefig(figs / "part3_ppl_vs_acc.png", dpi=200)
    plt.close(fig)
